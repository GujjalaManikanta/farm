const dicts: Record<Lang, Dict> = { te, en, hi, ta, kn, mr, bn, gu, pa };

const LangContext = createContext<{
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (key: string) => string;
  currentLangInfo: LanguageInfo;
}>({
  lang: "te",
  setLang: () => {},
  t: (k) => te[k] ?? en[k] ?? k,
  currentLangInfo: languages[0],
});

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(() => {
    if (typeof window !== "undefined") {
      const saved = localStorage.getItem("agri_app_language") as Lang;
      if (saved && dicts[saved]) return saved;
    }
    return "te"; // Default language is TELUGU
  });

  const setLang = (newLang: Lang) => {
    stopAllAudio();
    setLangState(newLang);
    if (typeof window !== "undefined") {
      localStorage.setItem("agri_app_language", newLang);
    }
  };

  const currentLangInfo = languages.find((l) => l.code === lang) ?? languages[0];
  const t = (key: string) => dicts[lang]?.[key] ?? te[key] ?? en[key] ?? key;

  return (
    <LangContext.Provider value={{ lang, setLang, t, currentLangInfo }}>
      {children}
    </LangContext.Provider>
  );
}

export const useLang = () => useContext(LangContext);
